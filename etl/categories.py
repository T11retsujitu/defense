CATEGORY_NAMES = [name for name, _, _ in CATEGORY_RULES] + [UNCLASSIFIED]
CATEGORY_SLUGS = {name: slug for name, slug, _ in CATEGORY_RULES}
CATEGORY_SLUGS[UNCLASSIFIED] = "uncategorized"


def classify(title: str) -> tuple[str, float]:
    """契約件名からカテゴリを決める。返り値: (カテゴリ名, 確信度)。"""
    if not title:
        return UNCLASSIFIED, 0.0
    text = title  # 原文(全角の型式番号あり)
    text_nfkc = nfkc(title)
    for name, _slug, keywords in CATEGORY_RULES:
        for kw in keywords:
            if isinstance(kw, re.Pattern):
                if kw.search(text) or kw.search(text_nfkc):
                    return name, 1.0
            else:
                if kw in text or nfkc(kw) in text_nfkc:
                    return name, 1.0
    return UNCLASSIFIED, 0.0
